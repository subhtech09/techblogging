/* ==========================================================================
   Client-side search over /search.json (generated by Jekyll at build time).
   GitHub Pages has no server, so the whole index is fetched once and
   searched in the browser — fast and plenty for a personal blog.
   ========================================================================== */
(function () {
  'use strict';

  var container = document.getElementById('search');
  if (!container) return;

  var input = document.getElementById('search-input');
  var status = document.getElementById('search-status');
  var results = document.getElementById('search-results');
  var browse = document.getElementById('search-browse');
  var form = container.querySelector('form');
  var index = null;
  var timer = null;

  function escapeHtml(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }

  function escapeRegExp(s) {
    return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  }

  // Terms match at the start of a word: "lake" finds "lakehouse",
  // but "merge" does not match inside "emergency".
  var WORD_START = '(?<![\\p{L}\\p{N}])';

  function termRegExp(term) {
    return new RegExp(WORD_START + escapeRegExp(term), 'iu');
  }

  // Wrap matches in <mark>, escaping everything else.
  function highlight(text, terms) {
    if (!text) return '';
    var re = new RegExp(WORD_START + '(' + terms.map(escapeRegExp).join('|') + ')', 'giu');
    return String(text).split(re).map(function (part, i) {
      return i % 2 ? '<mark>' + escapeHtml(part) + '</mark>' : escapeHtml(part);
    }).join('');
  }

  function loadIndex() {
    if (index) return Promise.resolve(index);
    return fetch(container.getAttribute('data-index'))
      .then(function (r) {
        if (!r.ok) throw new Error('HTTP ' + r.status);
        return r.json();
      })
      .then(function (data) { index = data; return data; });
  }

  // Every term must match somewhere; title and tag hits rank highest.
  function score(doc, terms) {
    var title = doc.title || '';
    var meta = (doc.tags || []).join(' ') + ' ' + (doc.topic || '');
    var desc = doc.description || '';
    var body = doc.content || '';
    var total = 0;
    for (var i = 0; i < terms.length; i++) {
      var re = termRegExp(terms[i]);
      var s = 0;
      if (re.test(title)) s += 10;
      if (re.test(meta)) s += 6;
      if (re.test(desc)) s += 4;
      if (re.test(body)) s += 1;
      if (s === 0) return 0;
      total += s;
    }
    return total;
  }

  function snippet(doc, terms) {
    var text = doc.content || '';
    var pos = -1;
    for (var i = 0; i < terms.length && pos === -1; i++) pos = text.search(termRegExp(terms[i]));
    if (pos === -1) return highlight(doc.description || text.slice(0, 180), terms);
    var start = Math.max(0, pos - 80);
    var excerpt = (start > 0 ? '…' : '') + text.slice(start, start + 220).trim() + '…';
    return highlight(excerpt, terms);
  }

  function render(query) {
    var terms = query.toLowerCase().split(/\s+/).filter(Boolean);
    if (!terms.length) {
      results.innerHTML = '';
      status.textContent = '';
      if (browse) browse.hidden = false;
      return;
    }

    loadIndex().then(function (docs) {
      var hits = docs
        .map(function (doc) { return { doc: doc, score: score(doc, terms) }; })
        .filter(function (h) { return h.score > 0; })
        .sort(function (a, b) { return b.score - a.score; });

      status.textContent = hits.length
        ? hits.length + (hits.length === 1 ? ' result' : ' results') + ' for “' + query + '”'
        : 'No articles match “' + query + '”. Try fewer or different words.';

      results.innerHTML = hits.map(function (h) {
        var d = h.doc;
        return '<li class="search-result"><a href="' + escapeHtml(d.url) + '">' +
          '<span class="search-result-meta">' + escapeHtml([d.topic, d.date].filter(Boolean).join(' · ')) + '</span>' +
          '<span class="search-result-title">' + highlight(d.title, terms) + '</span>' +
          '<span class="search-result-snippet">' + snippet(d, terms) + '</span>' +
          '</a></li>';
      }).join('');

      if (browse) browse.hidden = hits.length > 0;
    }).catch(function () {
      status.textContent = 'The search index could not be loaded. Please try again later.';
    });
  }

  function updateUrl(query) {
    var url = new URL(window.location.href);
    if (query) url.searchParams.set('q', query);
    else url.searchParams.delete('q');
    history.replaceState(null, '', url);
  }

  input.addEventListener('input', function () {
    clearTimeout(timer);
    timer = setTimeout(function () {
      var q = input.value.trim();
      updateUrl(q);
      render(q);
    }, 140);
  });

  form.addEventListener('submit', function (e) {
    e.preventDefault();
    var first = results.querySelector('a');
    if (first) first.focus();
  });

  var initial = new URLSearchParams(window.location.search).get('q');
  if (initial) {
    input.value = initial;
    render(initial.trim());
  } else {
    loadIndex().catch(function () {}); // warm the cache
  }
  input.focus();
})();
